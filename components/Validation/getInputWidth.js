const getInputWidth = (input) => {
  
  
  ///////////////////////////////// VALUES /////////////////////////////////

  const stdWidths = {
    // Numbers & Fractions
    ".": 3.3333333333333335,
    "1": 5,
    "2": 6.333333333333333,
    "3": 6.666666666666667,
    "4": 6.666666666666667,
    "5": 6.333333333333333,
    "6": 6.666666666666667,
    "7": 6,
    "8": 6.666666666666667,
    "9": 6.666666666666667,
    "0": 6.666666666666667,
    " ": 6,
    "/": 3.3333333333333335,

    // Lowercase
    a: 5.5, b: 6, c: 5.2, d: 6, e: 5.5, f: 3.3, g: 6, h: 6, i: 2.5, j: 2.5,
    k: 5.2, l: 2.5, m: 8.8, n: 6, o: 6, p: 6, q: 6, r: 3.8, s: 5, t: 3.3,
    u: 6, v: 5.2, w: 7.5, x: 5.2, y: 5.2, z: 5,

    // Uppercase
    A: 6.7, B: 6.7, C: 7.2, D: 7.2, E: 6.1, F: 5.8, G: 7.5, H: 7.2, I: 2.8,
    J: 5, K: 6.7, L: 5.5, M: 8.5, N: 7.2, O: 7.8, P: 6.7, Q: 7.8, R: 7.2,
    S: 6.7, T: 6.1, U: 7.2, V: 6.7, W: 9.5, X: 6.7, Y: 6.7, Z: 6.1,

    // Symbols & Punctuation
    "`": 3.3, "~": 6.7, "!": 3.3, "@": 10.5, "#": 6.7, "$": 6, "%": 9.5,
    "^": 5.2, "&": 7.2, "*": 4.2, "(": 3.8, ")": 3.8, "-": 3.8, "_": 6,
    "=": 6.7, "+": 6.7, "[": 3.3, "]": 3.3, "{": 3.8, "}": 3.8, "\\": 3.8,
    "|": 2.5, ";": 3.3, ":": 3.3, "'": 2.2, '"': 3.8, ",": 3.3, "<": 6.7,
    ">": 6.7, "?": 5.5,
  };
  
  
  ///////////////////////////////// FUNCTION /////////////////////////////////
  
  const splitInput = input?.split("") || [];
  const inputWidths = splitInput.map(char => stdWidths[char] || 0)
  const widthSum = inputWidths.reduce((sum, width) => sum + width, 0)
  return Math.max(6, Math.ceil(widthSum));
};
  
  
